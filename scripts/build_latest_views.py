def plot_graded(dest):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.ticker import MultipleLocator
    plt.rcParams.update({'font.family': 'serif', 'font.serif': ['DejaVu Serif'], 'font.size': 9,
                         'axes.labelsize': 9, 'axes.titlesize': 10, 'pdf.fonttype': 42})
    B = json.loads(EXPB.read_text())
    L = [0, 64, 128, 191, 255]
    fig, axs = plt.subplots(1, 2, figsize=(7.0, 2.3), sharey=True)
    for ax, (key, name) in zip(axs, [('qwen3-32b', 'Qwen3-32B'), ('qwen3.5-27b', 'Qwen3.5-27B')]):
        cells = B['receivers'][key]['phases']['development']['cells']
        for route, color, marker, ls, label in [('internal', '#236C9B', 'o', '-', 'Internal write (weight as strength)'),
                                                ('text', '#C67C32', 's', '--', 'Text (weight printed as [w/255])')]:
            J = [cells[f'{route}_L{l:03d}']['J']['family'] for l in L]
            ax.plot(L, [100 * j['mean'] for j in J], color=color, marker=marker, ms=3.5, lw=1.65, ls=ls, label=label, zorder=3)
            ax.fill_between(L, [100 * j['lo'] for j in J], [100 * j['hi'] for j in J], color=color, alpha=.12, linewidth=0)
        ax.set_title(name, pad=6)
        ax.set_xticks(L); ax.set_xlim(-8, 263); ax.set_ylim(-3, 104)
        ax.yaxis.set_major_locator(MultipleLocator(25)); ax.grid(axis='y', alpha=.18)
        ax.spines[['top', 'right']].set_visible(False); ax.tick_params(labelsize=8)
    axs[0].set_ylabel('Four-answer success (%)')
    fig.supxlabel('Weight $L$ of the competing value (own value at 255)', fontsize=9, y=.02)
    h, l = axs[0].get_legend_handles_labels()
    fig.legend(h, l, loc='upper center', ncol=2, frameon=False, bbox_to_anchor=(.53, 1.06), fontsize=8.5)
    fig.subplots_adjust(left=.08, right=.99, bottom=.22, top=.80, wspace=.08)
    fig.savefig(dest, bbox_inches='tight', metadata={'CreationDate': None, 'ModDate': None})
    plt.close(fig)


