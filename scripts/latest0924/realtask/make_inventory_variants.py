"""Experiment D: generate the two single-expression variants that accept the 275-symbol Countries inventory.

Each variant is the frozen file with exactly one inventory-size assertion changed from 221 to 275; nothing else differs
(asserted). The originals are untouched and remain pinned by Experiments A/B.
Usage: python3 scripts/latest0924/realtask/make_inventory_variants.py
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
EDITS = [
    ('src/syncomm/recovery/fit_layers.py', 'src/syncomm/recovery/fit_layers_inv275.py',
     "assert len(words) == 221 and len(set(words)) == len(words) and NEUTRAL_WORD not in words",
     "assert len(words) == 275 and len(set(words)) == len(words) and NEUTRAL_WORD not in words  # Experiment D inventory"),
    ('src/syncomm/latest/sender.py', 'src/syncomm/latest/sender_inv275.py',
     "assert len(words) == 221 and len(set(words)) == 221",
     "assert len(words) == 275 and len(set(words)) == 275  # Experiment D inventory"),
]
for src, dst, old, new in EDITS:
    s = (ROOT / src).read_text()
    assert s.count(old) == 1, (src, s.count(old))
    out = f'# GENERATED by scripts/latest0924/realtask/make_inventory_variants.py from {src} (sha256 {hashlib.sha256(s.encode()).hexdigest()}); one assertion changed (221 -> 275).\n' + s.replace(old, new)
    p = ROOT / dst
    if p.exists():
        assert p.read_text() == out, f'{dst} exists with different content'
    p.write_text(out)
    print(dst, hashlib.sha256(out.encode()).hexdigest()[:12])
