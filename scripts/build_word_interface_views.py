"""Render manuscript views of the frozen word-interface follow-up package.

Read audited estimates and intervals; do not fit, select configurations, run
inference, or recompute significance. The delivery-note dose-label typo is not
used: selected-dose and unit-dose embedding comparisons remain distinct.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'artifacts/word_interface_followup/results_package_v1'
PREFIX = '% GENERATED by scripts/build_word_interface_views.py from audited follow-up v1.\n'
MODELS = ['qwen3-32b', 'qwen3-14b-base', 'glm-4-9b', 'gemma-3-27b-it']
NAMES = ['Qwen3-32B', 'Qwen3-14B-Base', 'GLM-4-9B', 'Gemma-3-27B-IT']


def read(path):
    return json.loads(path.read_text())


# Supplement: files redacted for anonymity are mapped back to the digests recorded at analysis time.
_REDACTED = {v['redacted_sha256']: v['original_sha256'] for v in json.loads((ROOT / 'SANITIZATION.json').read_text())['files'].values()}


def digest(path):
    h = hashlib.sha256(path.read_bytes()).hexdigest()
    return h  # records carry the digests of the shipped files; SANITIZATION.json maps them to the originals


def pct(value):
    return f'{100 * value:.1f}'


def interval(row, stem='J', main=False):
    if stem == 'J':
        lo = min(row['J_group_lo'], row['J_template_lo'])
        hi = max(row['J_group_hi'], row['J_template_hi'])
        estimate = row['J']
    else:
        lo = min(row['family_lo'], row['template_lo'])
        hi = max(row['family_hi'], row['template_hi'])
        estimate = row['estimate']
    value = pct(estimate)
    if main or row.get('holm_reject'):
        value = r'\textbf{' + value + '}'
    return value + r'\enspace {\footnotesize [' + pct(lo) + ', ' + pct(hi) + ']}'


def table(label, caption, cols, header, rows, note, main=False, placement=None, compact=False):
    return PREFIX + '\n'.join([
        r'\begin{table}[' + (placement or ('H' if main else '!htbp')) + ']',
        r'\caption{\textbf{' + caption + '}}', r'\label{tab:' + label + '}',
        r'\centering' + (r'\normalsize' if main and not compact else r'\small'),
        r'\setlength{\tabcolsep}{' + ('3.5pt' if compact else '3pt') + r'}\renewcommand{\arraystretch}{1.12}',
        r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}' + cols + '@{}}',
        r'\toprule', header + r' \\', r'\midrule',
        *[' & '.join(row) + r' \\' for row in rows],
        r'\bottomrule', r'\end{tabular*}', r'\par\vspace{3pt}',
        r'{\footnotesize\raggedright ' + note + r'\par}', r'\end{table}', ''])


def render():
    provenance = read(PACKAGE / 'provenance.json')
    for item in provenance['inputs'].values():
        assert digest(ROOT / item['path']) == item['sha256'], item['path']
    for name, expected in provenance['locks'].items():
        assert digest(PACKAGE / 'locks' / name) == expected, name
    for name in ['p0a_dev', 'p0a_confirm']:
        assert not read(ROOT / provenance['inputs'][name]['path'])['partial']
    for name in ['p0b_dev', 'p0b_eval']:
        assert read(ROOT / provenance['inputs'][name]['path'])['status'] == 'PASS_INDEPENDENT_P0B_AUDIT'
    assert read(ROOT / provenance['inputs']['p0b_recount']['path'])['n_disagreements'] == 0
    # Preserve the documented floating-point tie discrepancy; do not relabel PASS.
    recount = read(ROOT / provenance['inputs']['p0a_recount']['path'])
    adjudication = read(PACKAGE / 'p0a_confirm_recount_adjudication.json')
    assert recount['status'] == 'FAIL_SECOND_COUNT_DISAGREES'
    assert adjudication['verdict'].startswith('ACCEPTED_WITH_DOCUMENTED_FLOAT_TIE')
    assert recount['n_disagreements'] == len(adjudication['residual']) == 4
    rows = read(PACKAGE / 'conditions_long.json')
    contrasts = read(PACKAGE / 'contrasts_long.json')
    selected = read(PACKAGE / 'locks/p0a_confirm.lock.json')['selected']
    gates = read(PACKAGE / 'claim_gate.json')['per_receiver']

    def condition(package, model, source, arm, gamma=None):
        stage = 'evaluation' if package == 'P0-B' else 'confirmation'
        found = [r for r in rows if r['package'] == package and r['stage'] == stage
                 and r['receiver'] == model and r['source'] == source and r['arm'] == arm
                 and (package != 'P0-B' or r['budget'] == 64)
                 and (gamma is None or r['gamma'] == gamma)]
        assert len(found) == 1, (package, model, source, arm, gamma)
        r = found[0]
        assert r['scenes'] == 576 and abs(r['J'] - r['J_numerator'] / 576) < 1e-12
        return r

    def contrast(package, model, name):
        stage = 'evaluation' if package == 'P0-B' else 'confirmation'
        found = [r for r in contrasts if r['package'] == package and r['stage'] == stage
                 and r['receiver'] == model and r['contrast'] == name]
        assert len(found) == 1, (package, model, name)
        return found[0]

    def mean(values):
        return sum(values) / len(values)

    files = {}
    main_rows, diagnostic_rows, paired_rows = [], [], []
    for model, name in zip(MODELS, NAMES):
        c = condition('P0-B', model, 'actual', 'selected')
        t = condition('P0-B', model, 'actual', 'packet_text')
        f = condition('P0-B', model, 'actual', 'full_text')
        sham = [condition('P0-B', model, 'actual', f'sham{i}') for i in range(3)]
        main_rows.append([name, r'\textbf{' + pct(c['J']) + '}', pct(t['J']), pct(f['J']),
                          pct(mean([r['J'] for r in sham])) + ' / ' + pct(mean([r['valid_rate'] for r in sham]))])
        assert gates[model]['reliable_automatic_conjunction_use'] == (model != 'glm-4-9b')
        for source, source_name in [('actual', 'Automatic'), ('literal', 'Complete facts')]:
            r = condition('P0-B', model, source, 'selected')
            text = condition('P0-B', model, source, 'packet_text')
            diagnostic_rows.append([name if source == 'actual' else '', source_name,
                                    f"{r['J_numerator']}/576", pct(r['accuracy']), pct(r['valid_rate']),
                                    pct(r['R']), pct(r['U']), pct(text['J'])])
        ct = contrast('P0-B', model, 'actual_selected_minus_packet_text')
        cr = contrast('P0-B', model, 'actual_selected_minus_mean_sham')
        assert cr['holm_reject']
        def binterval(r):
            return pct(r['estimate']) + ' [' + pct(min(r['group_lo'],r['template_lo'])) + ', ' + pct(max(r['group_hi'],r['template_hi'])) + ']'
        paired_rows.append([name, binterval(ct), binterval(cr),
                            '/'.join(pct(r['valid_rate']) for r in sham)])

    files['word_interface_conjunction.tex'] = table('wordif_conjunction',
        'Communicated facts support four-object conjunction queries.', 'lrrrr',
        r'Receiver & \textbf{Internal} & Text & \shortstack[r]{Full\\evidence} & \shortstack[r]{Reassigned\\Success / Valid}',
        main_rows,
        r'Four-answer success (\%) on 576 new scenes requiring color and material jointly. '
        r'Receiver configurations remain fixed. '
        r'Text renders the same automatic message; full evidence provides the original descriptions. '
        r'Intervals: Appendix~\ref{app:wordif_conjunction}. Reassigned averages three mappings. '
        r'Full controls: Appendix~\ref{app:wordif_conjunction}.', main=True, compact=True, placement='t')
    files['word_interface_conjunction_diagnostics.tex'] = table('wordif_conjunction_diagnostics',
        'Answer accuracy and selective use on conjunction queries.', 'llrrrrrr',
        r'Receiver & Message & \shortstack[r]{Joint\\count} & Accuracy & Valid & $R$ & $U$ & Text $J$',
        diagnostic_rows,
        r'All rates are percentages. Each source uses the same 576 scenes and 2,304 answers per receiver. '
        r'$R$ and $U$ require the changed and unchanged queries, respectively, correct in both worlds. '
        r'Complete facts contain the eight gold attributes without a model sender; all other settings remain fixed.')
    files['word_interface_conjunction_contrasts.tex'] = table('wordif_conjunction_contrasts',
        'Paired conjunction comparisons and reassignment validity.', 'lrrr',
        r'Receiver & \shortstack[r]{Internal $-$ text\\{[95\% CI]}} & \shortstack[r]{Internal $-$ reassigned\\{[95\% CI]}} & \shortstack[r]{Valid answers (\%)\\Draws 1 / 2 / 3}',
        paired_rows,
        r'Automatic messages; differences are percentage points. Intervals enclose the separately resampled '
        r'36-group and twelve-template intervals. Reassigned is the within-scene mean of three mappings. '
        r'All four reassignment contrasts pass the prespecified Holm correction; text differences are descriptive. '
        r'Low reassignment validity contributes to losses on Gemma and GLM; Qwen3-14B retains at least 99.8\% validity.')

    rep_rows, rep_contrasts, rep_main_rows = [], [], []
    for model, name in zip(MODELS, NAMES):
        for source, source_name in [('actual', 'Automatic'), ('literal', 'Complete facts')]:
            values = []
            for arm in ['c12', 'single_t0', 'single_t6', 'single_t11', 'emb1']:
                gamma = selected[model][arm]['gamma'] if isinstance(selected[model][arm], dict) else selected[model][arm]
                r = condition('P0-A', model, source, 'emb1' if arm == 'emb1' else 'w:' + arm, gamma)
                values.append(pct(r['J']))
            text = condition('P0-A', model, source, 'packet_text')
            emb1 = condition('P0-A', model, source, 'emb1', 1)
            assert emb1['J_numerator'] == text['J_numerator']
            assert emb1['single_token_share'] == 1
            rep_rows.append([name if source == 'actual' else '', source_name,
                             *values[:4], pct(text['J']), values[4]])
            if source == 'literal':
                rep_main_rows.append([name, *values[:4], pct(emb1['J'])])
            a1 = contrast('P0-A', model, f'{source}_A1_twelve_minus_mean_single_selected')
            a2 = contrast('P0-A', model, f'{source}_A2_twelve_minus_emb1_selected')
            rep_contrasts.append([name if source == 'actual' else '', source_name,
                                  interval(a1, stem='contrast'), interval(a2, stem='contrast')])
    files['word_interface_representations_main.tex'] = table('wordif_representations_main',
        'Local symbol directions and simpler representations.', 'lrrrrr',
        r'Receiver & \shortstack[r]{Twelve\\contexts} & \multicolumn{3}{c}{One fitting context} & '
        r'\shortstack[r]{Embedding\\(= text)} \\\cmidrule(lr){3-5}'
        '\n' + r' & & First & Middle & Last &',
        rep_main_rows,
        r'Complete-fact four-answer success (\%) on 576 new scenes. Direction strengths use the common '
        r'development grid: $\gamma=1$ except GLM First ($\gamma=4$). '
        r'Unit-strength input embeddings equal text for these single-token symbols. '
        r'Intervals and automatic messages: Appendix~\ref{app:wordif_representations}.',
        main=True, placement='!t')
    files['word_interface_representations.tex'] = table('wordif_representations',
        'Simple local representations on a separate two-object bank.', 'llrrrrrr',
        r'Receiver & Message & Twelve & First & Middle & Last & Text & Embedding',
        rep_rows,
        r'Four-answer success (\%) on 576 new scenes. First, Middle and Last use fitting contexts '
        r'0, 6 and 11 separately. Strengths are chosen on the same development grid: $\gamma=1$ throughout '
        r'except GLM First ($\gamma=4$) and Embedding ($\gamma=2$). Unit-strength embeddings exactly equal '
        r'Text on this single-token bank. Embedding denotes the selected-strength input-layer control, '
        r'not a projection into the internal writing layer.', placement='H')
    files['word_interface_representation_contrasts.tex'] = table('wordif_representation_contrasts',
        'What twelve-context fitting adds to the tested alternatives.', 'llrr',
        r'Receiver & Message & \shortstack[r]{Twelve $-$ mean single\\{[95\% CI]}} & \shortstack[r]{Twelve $-$ embedding\\{[95\% CI]}}',
        rep_contrasts,
        r'Paired percentage-point differences at each construction\textquotesingle s development-selected strength. '
        r'Intervals enclose family- and template-bootstrap intervals. Bold marks rejection after Holm correction '
        r'within each four-receiver comparison family, separately by message source. GLM embedding uses '
        r'$\gamma=2$; its unit-strength differences are $-6.6$ and $-16.3$ points for automatic and complete-fact '
        r'messages. No other receiver shows a corrected embedding difference.', placement='H')

    b = lambda model: condition('P0-B', model, 'actual', 'selected')
    numbers = {'WIConjScenes': '576', 'WIConjQwen': pct(b('qwen3-32b')['J']),
               'WIConjBase': pct(b('qwen3-14b-base')['J']), 'WIConjGLM': pct(b('glm-4-9b')['J']),
               'WIConjGemma': pct(b('gemma-3-27b-it')['J']),
               'WIConjRecall': pct(read(PACKAGE/'sender_content.json')['p0b_evaluation']['fact_recall']),
               'WIConjComplete': pct(read(PACKAGE/'sender_content.json')['p0b_evaluation']['complete_packet_rate'])}
    files['word_interface_numbers.tex'] = PREFIX + ''.join('\\newcommand{\\' + k + '}{' + v + '}\n' for k,v in numbers.items())
    meta = {'package': str(PACKAGE.relative_to(ROOT)), 'inputs': provenance['inputs'],
            'p0a_recount': adjudication['verdict'],
            'conditions_sha256': digest(PACKAGE/'conditions_long.json'),
            'contrasts_sha256': digest(PACKAGE/'contrasts_long.json'),
            'primary_scene_counts': {m:b(m)['J_numerator'] for m in MODELS},
            'note': 'No new model execution or statistical tests; tables use frozen exported contrasts.'}
    constants = {}
    for node in ast.parse((ROOT/'scripts/p0b_build_banks.py').read_text()).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            if node.targets[0].id in ['COLORS', 'MATERIALS', 'FRAMES', 'QUERIES']:
                constants[node.targets[0].id] = ast.literal_eval(node.value)
    bank = read(ROOT/'artifacts/word_interface_followup/p0b_banks/eval_bank.json')
    excluded = set(bank['engineering_scene_ids'])
    evaluation = [s for s in bank['scenes'] if s['scene'] not in excluded]
    assert len(evaluation) == 576
    for scene in evaluation:
        for world in scene['worlds']:
            for i, sentence in enumerate(world['evidence']):
                assert sentence == constants['FRAMES'][scene['template']].format(a=scene['aliases'][i], **world['facts'][i])
    context_spec = read(PACKAGE/'fitting_contexts.json')['constructions']
    spec = {
        'scope': 'Frozen word-interface follow-up; distinct from receiver-recovery confirmation.',
        'conjunction': {
            'evaluation_scenes': 576, 'separate_engineering_scenes': 4, 'development_scenes': 96,
            'colors': constants['COLORS'], 'materials': constants['MATERIALS'],
            'evidence_templates': constants['FRAMES'], 'query_templates': constants['QUERIES'],
            'groups': 36, 'scenes_per_group': 16, 'templates_crossed_with_groups': 12,
            'world_change': 'Exchange one attribute between two objects sharing the other attribute; retain all four combinations.',
            'component_ambiguity': 'Each queried color and material independently matches exactly two objects in either world.',
            'receivers': {m:{'zero_based_layers':json.loads(condition('P0-B',m,'actual','selected')['layers']), 'gamma':1} for m in MODELS},
            'sender': 'The existing four-object prompted Llama-3.1-8B-Instruct sender; questions and the counterworld are never supplied.',
            'primary_metric': 'All four answers correct: two questions in each of two worlds.',
            'primary_budget': 64, 'sensitivity_budget': 256,
            'intervals': 'Enclose separate 36-group and 12-template bootstrap intervals: 20,000 draws for each of three seeds.',
        },
        'representation_controls': {
            'confirmation_scenes': 576, 'separate_engineering_scenes':4,
            'single_contexts': context_spec['context_strings'], 'selected_strengths':selected,
            'input_embedding_location': 'Native input-embedding module, including receiver-specific scaling.',
            'unit_strength_identity': 'All active words are single tokens in their field context; embedding replacement equals packet text.',
            'multi_token_pooling_evaluated':False,
        },
        'availability': 'Specification only; full banks, executable code and raw predictions belong in the separate experiment archive.',
    }
    return files, meta, spec


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    files, meta, spec = render()
    destinations = {ROOT/'paper/tables'/name:text for name,text in files.items()}
    destinations[ROOT/'artifacts/paper_builds/word_interface_provenance.json'] = json.dumps(meta,indent=2)+'\n'
    destinations[ROOT/'paper/reproducibility/word_interface_followup_spec.json'] = json.dumps(spec,indent=2)+'\n'
    for path, text in destinations.items():
        if args.check:
            assert path.exists() and path.read_text() == text, path
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(text)
    print(('PASS' if args.check else 'WROTE'), len(destinations), 'word-interface manuscript artifacts')


if __name__ == '__main__':
    main()
