"""ADR-latest0924-moe-gate: build the engineering-phase variants used ONLY for Qwen3.5-122B-A10B.

Each variant is the pinned evaluator with exactly one expression replaced: the engineering `pass` flag drops the
max-logit-difference condition (still computed and stored in every row) and keeps alias-gap difference <= 0.1 and
equal parsed answers at both budgets. Everything else (identity-write inertness, reassignment norm match, resume drift,
L=255 world identity, pins) is byte-identical to the original. Development phases keep using the unmodified evaluators.
Usage: python3 scripts/latest0924/make_moe_gate_variants.py   (idempotent; prints sha256 of each variant)
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OLD = "checks['pass'] = checks['max_logit_difference'] <= .05 and checks['alias_gap_difference'] <= .1 and checks['parsed_equal']"
NEW = "checks['pass'] = checks['alias_gap_difference'] <= .1 and checks['parsed_equal']  # ADR-latest0924-moe-gate (122B only)"
for src, dst in [('src/syncomm/recovery/evaluate_confirm.py', 'src/syncomm/recovery/evaluate_confirm_moegate.py'),
                 ('src/syncomm/latest/evaluate_graded.py', 'src/syncomm/latest/evaluate_graded_moegate.py')]:
    s = (ROOT / src).read_text()
    assert s.count(OLD) == 1, (src, s.count(OLD))
    v = s.replace(OLD, NEW)
    header = f'# GENERATED by scripts/latest0924/make_moe_gate_variants.py from {src} (sha256 {hashlib.sha256(s.encode()).hexdigest()}); one expression replaced.\n'
    out = header + v
    p = ROOT / dst
    if p.exists():
        assert p.read_text() == out, f'{dst} exists with different content'
    p.write_text(out)
    print(dst, hashlib.sha256(out.encode()).hexdigest())
