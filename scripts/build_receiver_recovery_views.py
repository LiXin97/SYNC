"""Render audited receiver-recovery evidence, without fitting or model calls."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'artifacts/receiver_recovery/results_package_v2'
MODELS = ['qwen3-32b', 'qwen3-14b-base', 'glm-4-9b', 'gemma-3-27b-it']
NAMES = ['Qwen3-32B', 'Qwen3-14B-Base', 'GLM-4-9B', 'Gemma-3-27B-IT']
KEYS = ['Qwen', 'Base', 'GLM', 'Gemma']
RECOUNT = ROOT / 'review/receiver_recovery_recount.json'


# Supplement: files redacted for anonymity are mapped back to the digests recorded at analysis time.
_REDACTED = {v['redacted_sha256']: v['original_sha256'] for v in json.loads((ROOT / 'SANITIZATION.json').read_text())['files'].values()}


def digest(p):
    h = hashlib.sha256(p.read_bytes()).hexdigest()
    return h  # records carry the digests of the shipped files; SANITIZATION.json maps them to the originals


def pct(v):
    return f'{100*v:.1f}'


def table(name, title, columns, headings, rows, note, main=False, placement=None, compact=False):
    return '\n'.join([
        '% GENERATED by scripts/build_receiver_recovery_views.py; audited package v2.',
        r'\begin{table}[' + (placement or ('H' if main else '!htbp')) + ']', r'\caption{\textbf{' + title + '}}',
        r'\label{tab:' + name + '}', r'\centering' + (r'\normalsize' if main and not compact else r'\small'),
        r'\setlength{\tabcolsep}{' + ('3.5pt' if compact else '3pt') + r'}\renewcommand{\arraystretch}{' + ('1.12' if compact else '1.16' if main else '1.08') + '}',
        r'\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}' + columns + '@{}}',
        r'\toprule', headings + r' \\', r'\midrule',
        *[' & '.join(row) + r' \\' for row in rows],
        r'\bottomrule', r'\end{tabular*}', r'\par\vspace{3pt}',
        r'{\footnotesize\raggedright ' + note + r'\par}', r'\end{table}', ''])


def render():
    provenance = json.loads((PACKAGE/'provenance.json').read_text())
    for name, info in provenance['audits'].items():
        assert digest(PACKAGE.parent/name) == info['sha256']
        assert info['status'].startswith('PASS')
    for name, want in provenance['locks'].items():
        assert digest(PACKAGE/'locks'/name) == want
    rows = json.loads((PACKAGE/'conditions_long.json').read_text())
    contrasts = json.loads((PACKAGE/'contrasts_long.json').read_text())
    selection = json.loads((PACKAGE/'selection.json').read_text())

    def get(stage, model, source, arm, **filters):
        v = [x for x in rows if x['stage'] == stage and x['receiver'] == model
             and x['source'] == source and x['arm'] == arm and x['budget'] == 64
             and all(x[k] == value for k, value in filters.items())]
        assert len(v) == 1, (stage, model, source, arm, filters)
        return v[0]

    def point(x):
        return pct(x['all_four_family_mean'])

    def interval(x):
        return '[' + pct(x['all_four_family_lo']) + ', ' + pct(x['all_four_family_hi']) + ']'

    macros = [r'\newcommand{\RECScenes}{572}', r'\newcommand{\RECDevScenes}{92}',
              r'\newcommand{\RECFourScenes}{188}']
    main, capacity, native_rows, details, paired, cost_rows = [], [], [], [], [], []
    for model, name, key in zip(MODELS, NAMES, KEYS):
        assert selection['receivers'][model]['selected']['depth'] == .2
        assert selection['receivers'][model]['selected']['gamma'] == 1
        old = get('R3', model, 'actual', 'original')
        new = get('R3', model, 'actual', 'selected')
        txt = get('R3', model, 'actual', 'packet_text')
        shams = [get('R3', model, 'actual', f'sham{i}') for i in range(3)]
        assert old['scenes'] == new['scenes'] == txt['scenes'] == 572
        sh = pct(sum(x['all_four_family_mean'] for x in shams)/3)
        sh_valid = pct(sum(x['coverage_family_mean'] for x in shams)/3)
        main.append([name, point(old), r'\textbf{' + point(new) + r'}\enspace {\footnotesize ' + interval(new) + '}', point(txt), sh + ' / ' + sh_valid])
        for suffix, value in [('Rate', point(new)), ('Text', point(txt)),
                              ('Lo', pct(new['all_four_family_lo'])), ('Hi', pct(new['all_four_family_hi'])),
                              ('Related', pct(new['relevant_both_family_mean'])), ('Unchanged', pct(new['unrelated_both_family_mean']))]:
            macros.append(r'\newcommand{\REC' + key + suffix + '}{' + value + '}')
        capacity.append([name] + [point(get('R3', model, 'literal', a)) for a in ['original','selected','native','packet_text','full_text']])
        native_delta = [x for x in contrasts if x['stage'] == 'R3'
                        and x['receiver'] == model
                        and x['contrast'] == 'literal_selected_minus_native']
        assert len(native_delta) == 1
        delta = native_delta[0]
        native_rows.append([
            name,
            r'\textbf{' + point(get('R3', model, 'literal', 'selected')) + '}',
            point(get('R3', model, 'literal', 'native')),
            f"{100*delta['family_mean']:+.1f} [{100*delta['family_lo']:+.1f}, {100*delta['family_hi']:+.1f}]",
            point(get('R3', model, 'literal', 'packet_text'))])
        for arm, label in [('selected', 'Early write'), ('packet_text', 'Same packet as text'), ('sham0', 'Reassignment 1'), ('sham1', 'Reassignment 2'), ('sham2', 'Reassignment 3')]:
            x = get('R3', model, 'actual', arm)
            details.append([name if arm == 'selected' else '', label, point(x), pct(x['accuracy_family_mean']), pct(x['coverage_family_mean']), pct(x['relevant_both_family_mean']), pct(x['unrelated_both_family_mean'])])
        for contrast, label in [('actual_selected_minus_original', 'Early minus middle'),
                                ('actual_selected_minus_mean_sham', 'Early minus reassigned'),
                                ('actual_selected_minus_packet_text', 'Early minus text')]:
            x = next(x for x in contrasts if x['stage'] == 'R3' and x['receiver'] == model and x['contrast'] == contrast)
            paired.append([name if 'original' in contrast else '', label, pct(x['family_mean']),
                           f"[{pct(x['family_lo'])}, {pct(x['family_hi'])}]", f"[{pct(x['template_lo'])}, {pct(x['template_hi'])}]"])
        cost = json.loads((PACKAGE/'cost.json').read_text())[model]['receiver_side']
        w, t = cost['write'], cost['text']
        cost_rows.append([name, f"{w['warm_median_ms']:.0f}", f"{w['warm_p90_ms']:.0f}", f"{t['warm_median_ms']:.0f}", f"{t['warm_p90_ms']:.0f}"])

    files = {'receiver_recovery_main.tex': table('recovery_main', 'Automatic fact communication across receiver families.', 'lrrrr',
        r'Receiver & Middle & \textbf{Early [95\% CI]} & Text & \shortstack[r]{Reassigned\\Success / Valid}', main,
        r'Four-answer success (\%) on 572 scenes, averaged over 36 material families. '
        r'One Llama-3.1-8B-Instruct sender supplies the same messages to all routes. '
        r'Brackets give family-bootstrap intervals. Reassigned: success / valid answers, averaged '
        r'over three edit-norm-matched reassignments. '
        r'Invalid answers count as errors; without a message, success is zero by construction. '
        r'Full results: Appendix~\ref{app:receiver_recovery}.', main=True)}
    files['receiver_recovery_native.tex'] = table('recovery_native',
        'Reusable symbol directions and the receiver\'s own states.', 'lrrrr',
        r'Receiver & \textbf{Directions} & Native states & Difference [95\% CI] & Text', native_rows,
        r'Complete-fact four-answer success (\%) on 572 confirmation scenes, with no model sender. '
        r'Native states come from the receiver reading each scene\textquotesingle s facts; both routes write '
        r'at the same early layer and fact positions. Differences are directions minus native states '
        r'(percentage points), with paired family-bootstrap intervals. Text reads the same facts. '
        r'Closeness does not establish equivalence.', main=True, compact=True,
        placement='!htbp')  # appendix since 2026-09-25 (PI-approved restructure)
    four = []
    for model, name, key in zip(MODELS, NAMES, KEYS):
        if model not in ['qwen3-32b', 'gemma-3-27b-it']:
            continue
        x = get('R4', model, 'actual', 'selected')
        assert x['scenes'] == 188
        four.append([name, r'\textbf{' + point(x) + r'}\enspace {\footnotesize ' + interval(x) + '}',
                     point(get('R4', model, 'actual', 'packet_text')),
                     point(get('R4', model, 'literal', 'selected'))])
        macros.append(r'\newcommand{\REC' + key + 'Four}{' + point(x) + '}')
    files['receiver_recovery_four.tex'] = table('recovery_four', 'The fixed receiver configuration extends to four objects.', 'lrrr',
        r'Receiver & \shortstack[r]{Automatic write\\{[95\% CI]}} & \shortstack[r]{Same-message\\text} & \shortstack[r]{Complete-fact\\write}', four,
        r'Four-answer success (\%) on 188 four-object scenes, with 24-family intervals. '
        r'Receiver dictionaries, depth and strength are unchanged; the sender schema is extended to four objects. '
        r'Complete facts have no model sender. This descriptive extension uses four templates; their wider intervals '
        r'and receiver selection are reported in Appendix~\ref{app:recovery_four}.')
    files['receiver_recovery_capacity.tex'] = table('recovery_capacity', 'Complete facts and contextual states at the selected depth.', 'lrrrrr',
        r'Receiver & Middle write & Early write & Native states & Packet text & Evidence text', capacity,
        r'Four-answer success (\%) on the same 572-scene bank. All conditions supply complete facts without a model sender. '
        r'Native states are the receiver\textquotesingle s own contextual fact-token states, transplanted at the selected early layer. '
        r'All conditions use four public positions per object.')
    files['receiver_recovery_controls.tex'] = table('recovery_controls', 'Answer validity and selective use in automatic confirmation.', 'llrrrrr',
        r'Receiver & Delivery & Joint & Accuracy & Valid & Changed & Unchanged', details,
        r'Percentages are family-macro averages on 572 scenes. Accuracy scores individual answers; two-choice chance is 50\%. '
        r'Valid is the fraction of answers following the required format, regardless of correctness. '
        r'Changed and unchanged each require the respective question '
        r'to be correct in both worlds. Invalid generations remain errors. The 256-token sensitivity does not change joint success.')
    files['receiver_recovery_contrasts.tex'] = table('recovery_contrasts', 'Paired gains under both clustering levels.', 'llrrr',
        r'Receiver & Contrast & Gain (pp) & 36-family interval & 12-template interval', paired,
        r'95\% paired bootstrap intervals. Early-minus-middle and early-minus-mean-reassignment on Qwen3-14B-Base, '
        r'GLM-4-9B and Gemma-3-27B-IT form the six-test Holm family; all six reject. Text contrasts are descriptive; '
        r'a small or zero difference does not establish equivalence.')
    files['receiver_recovery_cost.tex'] = table('recovery_cost', 'Receiver-side delivery cost for complete-fact messages.', 'lrrrr',
        r' & \multicolumn{2}{c}{Early write (ms)} & \multicolumn{2}{c}{Text (ms)} \\\cmidrule(lr){2-3}\cmidrule(l){4-5} Receiver & Median & p90 & Median & p90', cost_rows,
        r'One B200, FP32 eager, batch one, 64-token budget; each item answers two questions. '
        r'Eight development scenes yield sixteen world-items, each repeated five times; four warm repetitions are summarized. '
        r'These use supplied complete facts, not actual automatic packets. Sender generation and offline fitting are excluded.')
    files['receiver_recovery_numbers.tex'] = '\n'.join(macros) + '\n'
    return files, rows


def plot(rows):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from matplotlib.ticker import MultipleLocator
    plt.rcParams.update({'font.family':'serif', 'font.serif':['DejaVu Serif'], 'font.size':9,
                         'axes.labelsize':9, 'axes.titlesize':10, 'pdf.fonttype':42})
    fig, axs = plt.subplots(1, 4, figsize=(7.0, 2.35), sharex=True, sharey=True)
    depths = [.2, .35, .5, .65, .8]
    for ax, model, name in zip(axs, MODELS, NAMES):
        for arm, color, marker, label in [('fitted', '#236C9B', 'o', 'Fitted symbol directions'),
                                           ('native', '#C67C32', 's', 'Native fact states')]:
            data = []
            for depth in ['d20', 'd35', 'd50', 'd65', 'd80']:
                x = [x for x in rows if x['stage']=='R1' and x['receiver']==model and x['source']=='literal'
                     and x['arm']==arm and x['depth_label']==depth and x['budget']==64 and (arm=='native' or x['gamma']==1)]
                assert len(x)==1
                data.append(x[0])
            ax.plot(depths, [100*x['all_four_family_mean'] for x in data], color=color, marker=marker,
                    ms=3.5, lw=1.65, ls='-' if arm=='fitted' else '--', label=label, zorder=3)
            ax.fill_between(depths, [100*x['all_four_family_lo'] for x in data],
                            [100*x['all_four_family_hi'] for x in data], color=color, alpha=.10, linewidth=0)
        ax.set_title(name, pad=7)
        ax.axvline(.2, color='#9BADB9', lw=.7, ls=':', zorder=0)
        ax.set_xticks([.2,.5,.8]); ax.set_ylim(-3,104); ax.set_xlim(.17,.83)
        ax.yaxis.set_major_locator(MultipleLocator(50));ax.grid(axis='y',alpha=.18)
        ax.spines[['top','right']].set_visible(False)
        ax.tick_params(labelsize=8)
    axs[0].set_ylabel('Four-answer success (%)')
    fig.supxlabel('Relative write depth', fontsize=9, y=.03)
    handles, labels = axs[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', ncol=2, frameon=False, bbox_to_anchor=(.53,1.025), fontsize=9)
    fig.subplots_adjust(left=.078,right=.994,bottom=.23,top=.75,wspace=.20)
    dest = ROOT/'paper/figures/receiver_recovery_depth.pdf'
    fig.savefig(dest, bbox_inches='tight', metadata={'CreationDate':None,'ModDate':None})
    plt.close(fig)


def error_counts(rows):
    """Read the independent scene/packet cross-tab; classify failures, not causes."""
    recount = json.loads(RECOUNT.read_text())
    output = []
    for model, name in [(MODELS[0], NAMES[0]), (MODELS[3], NAMES[3])]:
        audit = recount['r4/' + model]
        for key in ['raw_receipt_hash_errors', 'parse_errors', 'gold_errors', 'export_disagreements']:
            assert not audit[key], (model, key)
        summary = audit['conditions']['actual/selected']
        exported = [r for r in rows if r['stage'] == 'R4' and r['receiver'] == model
                    and r['source'] == 'actual' and r['arm'] == 'selected' and r['budget'] == 64]
        assert len(exported) == 1
        assert summary['n'] == exported[0]['scenes'] == 188
        assert abs(summary['J_family_mean'] - exported[0]['all_four_family_mean']) < 1e-12
        missing, complete, successes, total = 0, 0, 0, 0
        for key, n in audit['packet_error_cross_tab'].items():
            fields = dict(part.split('=') for part in key.split(','))
            total += n
            if fields['write'] == '1':
                successes += n
            elif fields['query'] == 'False':
                missing += n
            else:
                assert fields['complete'] == 'True', key
                complete += n
        assert total == summary['n']
        assert successes == summary['successes']
        assert missing + complete == total - successes
        output.append(dict(receiver=model, name=name, scenes=total, successes=successes,
                           missing_queried_fact=missing, all_facts_present=complete))
    return output


def plot_strength_grid(rows):
    import matplotlib.pyplot as plt
    import numpy as np
    from matplotlib.colors import LinearSegmentedColormap
    from matplotlib.patches import Patch, Rectangle
    depths = ['d20', 'd35', 'd50', 'd65', 'd80']
    strengths = [.25, .5, 1, 2, 4]
    cmap = LinearSegmentedColormap.from_list('local_word_success', ['#F7FAFC', '#7EB2CE', '#205F87'])
    fig, axs = plt.subplots(1, 4, figsize=(5.5, 1.9), sharey=True)
    for ax, model, name in zip(axs, MODELS, NAMES):
        values, coverage = [], []
        for strength in strengths:
            row, cov = [], []
            for depth in depths:
                found = [x for x in rows if x['stage'] == 'R1' and x['receiver'] == model
                         and x['source'] == 'literal' and x['arm'] == 'fitted'
                         and x['budget'] == 64 and x['depth_label'] == depth and x['gamma'] == strength]
                assert len(found) == 1
                assert found[0]['scenes'] == 92
                row.append(100 * found[0]['all_four_family_mean'])
                cov.append(found[0]['coverage_family_mean'])
            values.append(row); coverage.append(cov)
        values = np.asarray(values)
        im = ax.imshow(values, vmin=0, vmax=100, cmap=cmap, aspect='auto', interpolation='nearest')
        for i in range(5):
            for j in range(5):
                if coverage[i][j] < .9:
                    ax.add_patch(Rectangle((j-.5, i-.5), 1, 1, facecolor='none',
                                           hatch='//', edgecolor='#B0BAC1', lw=0))
                ax.text(j, i, f'{values[i,j]:.0f}', ha='center', va='center', fontsize=7.4,
                        color='white' if values[i,j] >= 60 else '#1D2730')
        ax.add_patch(Rectangle((-.47, 1.53), .94, .94, fill=False, edgecolor='#C67C32', lw=1.8))
        ax.set_title(name, fontsize=8.7, pad=6)
        ax.set_xticks(range(5), ['.2', '.35', '.5', '.65', '.8'], fontsize=7.8)
        ax.set_yticks(range(5), ['.25', '.5', '1', '2', '4'], fontsize=8)
        ax.tick_params(length=0, pad=3)
        ax.set_xticks(np.arange(-.5, 5, 1), minor=True)
        ax.set_yticks(np.arange(-.5, 5, 1), minor=True)
        ax.grid(which='minor', color='white', linewidth=.6)
        ax.tick_params(which='minor', length=0)
        for spine in ax.spines.values(): spine.set_visible(False)
    axs[0].set_ylabel(r'Strength $\gamma$', fontsize=9, labelpad=3)
    fig.subplots_adjust(left=.08, right=.91, bottom=.31, top=.82, wspace=.17)
    cax = fig.add_axes([.93, .31, .018, .51])
    cb = fig.colorbar(im, cax=cax, ticks=[0, 50, 100]); cb.ax.tick_params(labelsize=7.8, length=2)
    cb.outline.set_visible(False)
    fig.text(.49, .16, 'Relative write depth', ha='center', fontsize=9)
    fig.legend(handles=[Patch(facecolor='white', hatch='//', edgecolor='#B0BAC1', label='Coverage <90%'),
                        Patch(facecolor='white', edgecolor='#C67C32', lw=1.8, label='Selected configuration')],
               loc='lower center', bbox_to_anchor=(.52, -.025), frameon=False, ncol=2, fontsize=8)
    fig.savefig(ROOT/'paper/figures/receiver_recovery_strength.pdf', bbox_inches='tight',
                metadata={'CreationDate':None, 'ModDate':None})
    plt.close(fig)


def plot_errors(counts):
    import matplotlib.pyplot as plt
    from matplotlib.patches import Patch
    fig, ax = plt.subplots(figsize=(5.5, 1.35))
    for y, row in enumerate(counts):
        a, b = row['missing_queried_fact'], row['all_facts_present']
        ax.barh(y, a, height=.48, color='#C67C32', zorder=3)
        ax.barh(y, b, left=a, height=.48, color='#236C9B', zorder=3)
        ax.text(a/2, y, str(a), color='white', ha='center', va='center', fontsize=10, weight='bold')
        ax.text(a+b/2 if b else a+.7, y, str(b), color='white' if b else '#236C9B',
                ha='center', va='center', fontsize=10, weight='bold')
    ax.set_yticks(range(len(counts)), [r['name'] for r in counts], fontsize=9)
    ax.invert_yaxis(); ax.set_xlim(0,27)
    ax.set_xticks([0,5,10,15,20,25]); ax.tick_params(axis='both', length=0, labelsize=8.5)
    ax.set_xlabel('Failed scenes (out of 188)', fontsize=9, labelpad=3)
    ax.grid(axis='x', alpha=.16, zorder=0)
    ax.spines[['top','right','left']].set_visible(False)
    ax.spines['bottom'].set_color('#C4CDD4')
    fig.legend(handles=[Patch(color='#C67C32', label='Missing queried fact'),
                        Patch(color='#236C9B', label='All facts present')],
               loc='upper center', bbox_to_anchor=(.61,1.04), frameon=False, ncol=2, fontsize=8.5)
    fig.subplots_adjust(left=.245, right=.98, bottom=.3, top=.72)
    fig.savefig(ROOT/'paper/figures/receiver_recovery_errors.pdf', bbox_inches='tight',
                metadata={'CreationDate':None, 'ModDate':None})
    plt.close(fig)


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--tables-only', action='store_true', help='Preserve existing figure assets when updating table placement.')
    args = ap.parse_args()
    files, rows = render()
    for name, body in files.items():
        path = ROOT/'paper/tables'/name
        if args.check:
            assert path.read_text() == body, f'Stale {path}'
        else:
            path.write_text(body)
    counts = error_counts(rows)
    if not args.check and not args.tables_only:
        plot(rows)
        plot_strength_grid(rows)
        plot_errors(counts)
    source_names = ['provenance.json','conditions_long.json','contrasts_long.json','selection.json','cost.json']
    record = {'package':'receiver_recovery/results_package_v2',
              'renderer_sha256':digest(Path(__file__)),
              'sources':{name:digest(PACKAGE/name) for name in source_names},
              'independent_recount':{'path':str(RECOUNT.relative_to(ROOT)), 'sha256':digest(RECOUNT)},
              'four_object_error_counts':counts,
              'outputs':{str((Path('paper/tables')/name)):digest(ROOT/'paper/tables'/name) for name in files},
              'figures':{f'receiver_recovery_{name}.pdf':digest(ROOT/f'paper/figures/receiver_recovery_{name}.pdf')
                         for name in ['depth','strength','errors']}}
    path = ROOT/'artifacts/paper_builds/receiver_recovery_provenance.json'
    if args.check:
        assert json.loads(path.read_text()) == record
    else:
        path.write_text(json.dumps(record,indent=2)+'\n')
    print(('Verified' if args.check else 'Generated'),len(files),'tables/macros and three result figures')
