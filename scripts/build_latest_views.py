def predict_summary():
    """Recount the Experiment F scoring from the per-cell records (never trust the stored aggregate alone)."""
    S = json.loads(PRED.read_text()); P = json.loads(PREDICTIONS.read_text())
    assert S['predictions_sha256'] and abs(S['tau'] - P['tau']) < 1e-12 and S['d_star'] == P['d_star']
    cells = {(c['receiver'], c['depth']): c for c in S['cells']}
    assert len(cells) == 45 and set(k for k, _ in cells) == {k for k, _, _ in HELDOUT}
    for c in cells.values():
        assert c['pred'] == (c['metric'] >= S['tau']) and c['usable'] == (c['J'] >= 50) and c['depth_only'] == (c['depth'] <= S['d_star'])
    correct = sum(c['pred'] == c['usable'] for c in cells.values())
    wrong_depth_only = sorted((k, d) for (k, d), c in cells.items() if c['depth_only'] != c['usable'])
    assert correct == round(S['results']['accuracy'] * 45)
    return S, P, cells, correct, wrong_depth_only


